from pathlib import Path
from typing import Any, Optional

import httpx

from core.config import get_settings, save_env_var, reload_settings

logger = logging.getLogger(__name__)

# ---------------------------------------------------------------------------
# Constants
# ---------------------------------------------------------------------------
# Mojang Vanilla API
MOJANG_MANIFEST_URL = "https://piston-meta.mojang.com/mc/game/version_manifest_v2.json"
USER_AGENT = "NusatopiaManager/1.0 (github.com/Hasboy15S/Nusatopia)"
STOP_TIMEOUT = 30          # seconds to wait for graceful stop before force-kill
CRASH_POLL_INTERVAL = 3    # seconds between crash-detection polls
MAX_COMMAND_LEN = 256       # maximum bytes accepted from WebSocket command input
LOG_MAX_BYTES = 10 * 1024 * 1024   # 10 MB per rotating log slice
LOG_BACKUP_COUNT = 5


# ---------------------------------------------------------------------------
# Server status enum
# ---------------------------------------------------------------------------
class ServerStatus(str, Enum):
    OFFLINE = "Offline"
    STARTING = "Starting"
    RUNNING = "Running"
    STOPPING = "Stopping"
    CRASHED = "Crashed"


# ---------------------------------------------------------------------------
# WebSocket connection manager (console broadcast)
# ---------------------------------------------------------------------------
class ConnectionManager:
    """Tracks active WebSocket connections and fans out console lines."""

    def __init__(self) -> None:
        self._connections: set[Any] = set()
        self._lock = asyncio.Lock()

    async def connect(self, ws: Any) -> None:
        await ws.accept()
        async with self._lock:
            self._connections.add(ws)

    async def disconnect(self, ws: Any) -> None:
        async with self._lock:
            self._connections.discard(ws)

    async def broadcast(self, message: str) -> None:
        if not self._connections:
            return
        dead: set[Any] = set()
        async with self._lock:
            connections = set(self._connections)
        for ws in connections:
            try:
                await ws.send_text(message)
            except Exception:  # noqa: BLE001
                dead.add(ws)
        if dead:
            async with self._lock:
                self._connections -= dead


