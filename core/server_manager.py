"""
core/server_manager.py
======================
Central controller for the Minecraft server subprocess lifecycle.

Responsibilities
----------------
â€¢ Download PaperMC jar if absent (via PaperMC v3 API (fill.papermc.io))
â€¢ Write eula.txt and a default server.properties
â€¢ Spawn / stop / kill the Java process
â€¢ Read STDOUT/STDERR in a background thread and broadcast to WebSocket clients
â€¢ Persist console output to a rotating log file
â€¢ Crash detection via a polling background task
â€¢ In-memory state machine: Offline â†’ Starting â†’ Running â†’ Stopping â†’ Crashed

Lifecycle safety
----------------
On FastAPI shutdown we GRACEFULLY STOP the Minecraft process (send 'stop',
wait up to STOP_TIMEOUT seconds, then terminate/kill).
Rationale: an abrupt shutdown risks world corruption. A graceful stop ensures
Minecraft flushes chunk data before the process exits, at the cost of a
slightly longer shutdown time.

Never allow two processes: a threading.Lock guards the start sequence.
"""

