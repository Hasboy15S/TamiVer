"""
core/server_manager.py
======================
Central controller for the Minecraft server subprocess lifecycle.

Responsibilities
----------------
â€¢ Download PaperMC jar if absent (via PaperMC v3 API (fill.papermc.io))
â€¢ Write eula.txt and a default server.properties
â€¢ Spawn / stop / kill the Java process
â€¢ Read STDOUT/STDERR in a background thread and broadcast to WebSocket clients
â€¢ Persist console output to a rotating log file
â€¢ Crash detection via a polling background task
â€¢ In-memory state machine: Offline â†’ Starting â†’ Running â†’ Stopping â†’ Crashed

Lifecycle safety
----------------
On FastAPI shutdown we GRACEFULLY STOP the Minecraft process (send 'stop',
wait up to STOP_TIMEOUT seconds, then terminate/kill).
Rationale: an abrupt shutdown risks world corruption. A graceful stop ensures
Minecraft flushes chunk data before the process exits, at the cost of a
slightly longer shutdown time.

Never allow two processes: a threading.Lock guards the start sequence.
"""

from __future__ import annotations

import asyncio
import logging
import os
import queue
import subprocess
import threading
import time
from datetime import datetime, timezone
from enum import Enum
from logging.handlers import RotatingFileHandler
from pathlib import Path
from typing import Any, Optional

import httpx

from core.config import get_settings

logger = logging.getLogger(__name__)

# ---------------------------------------------------------------------------
# Constants
# ---------------------------------------------------------------------------
# PaperMC migrated from api.papermc.io/v2 (sunset) to fill.papermc.io/v3
PAPERMC_API_BASE   = "https://fill.papermc.io/v3/projects/paper"
PAPERMC_USER_AGENT = "NusatopiaManager/1.0 (github.com/Hasboy15S/Nusatopia)"
FALLBACK_JAR_URL   = "https://fill-data.papermc.io/v1/objects/05209ac5a423bf98136dd775a87d4324955d2c865f887b20edd6b43a59cb36c4/paper-1.21.4-1.jar"
STOP_TIMEOUT = 30          # seconds to wait for graceful stop before force-kill
CRASH_POLL_INTERVAL = 3    # seconds between crash-detection polls
MAX_COMMAND_LEN = 256       # maximum bytes accepted from WebSocket command input
LOG_MAX_BYTES = 10 * 1024 * 1024   # 10 MB per rotating log slice
LOG_BACKUP_COUNT = 5


# ---------------------------------------------------------------------------
# Server status enum
# ---------------------------------------------------------------------------
class ServerStatus(str, Enum):
    OFFLINE = "Offline"
    STARTING = "Starting"
    RUNNING = "Running"
    STOPPING = "Stopping"
    CRASHED = "Crashed"


# ---------------------------------------------------------------------------
# WebSocket connection manager (console broadcast)
# ---------------------------------------------------------------------------
class ConnectionManager:
    """Tracks active WebSocket connections and fans out console lines."""

    def __init__(self) -> None:
        self._connections: set[Any] = set()
        self._lock = asyncio.Lock()

    async def connect(self, ws: Any) -> None:
        await ws.accept()
        async with self._lock:
            self._connections.add(ws)

    async def disconnect(self, ws: Any) -> None:
        async with self._lock:
            self._connections.discard(ws)

    async def broadcast(self, message: str) -> None:
        if not self._connections:
            return
        dead: set[Any] = set()
        async with self._lock:
            connections = set(self._connections)
        for ws in connections:
            try:
                await ws.send_text(message)
            except Exception:  # noqa: BLE001
                dead.add(ws)
        if dead:
            async with self._lock:
                self._connections -= dead


